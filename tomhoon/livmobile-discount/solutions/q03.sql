-- Q03. 전월과 당월 할인 대상 비교
-- 핵심: GROUP BY 없이 COUNT(DISTINCT CASE WHEN ...)으로 월을 컬럼으로 펼침 -> 1행
--       (GROUP BY BILL_YYMM을 쓰면 2행이 되어 틀림)
-- 검증: PREV_CNT = 280, CURR_CNT = 203

SELECT COUNT(DISTINCT CASE WHEN BILL_YYMM = '202610' THEN CTRT_ID END) AS PREV_CNT
     , COUNT(DISTINCT CASE WHEN BILL_YYMM = '202611' THEN CTRT_ID END) AS CURR_CNT
  FROM KB_DISCOUNT_INFO
 WHERE BILL_YYMM IN ('202610', '202611');

